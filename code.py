a = float(input("Первое число:"))
operation = input("Операция (+, -, *, /): ")
b = float(input("Второе число: "))

if operation == "+":
    print (a + b)
elif operation == "-":
    print (a - b)
elif operation == "*":
    print (a * b)
elif operation == "/":
    print (a / b)

